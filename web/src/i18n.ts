export type MessageKey = keyof typeof tr;

const messages: Record<Lang, Record<MessageKey, string>> = { tr, en };

/** Sozlukten metin; `{ad}` yer tutuculari doldurulur. */
export function translate(
  lang: Lang,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let text = messages[lang][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

/**
 * Baslik/etiket icin buyuk harf. Turkce metinlerde i -> İ kurali uygulanir
 * (disk -> DİSK). CSS `text-transform` bu kurali uygulamaz; bu yuzden
 * dil bilincli cevrim kullanilir.
 */
export function translateUpper(
  lang: Lang,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  return translate(lang, key, vars).toLocaleUpperCase(lang === 'tr' ? 'tr-TR' : 'en-US');
}
